-- CTEs [COMMON TABLE EXPRESSION]


-- 1

WITH CTE_TABLE AS
(
SELECT 
	*
FROM
	dim_product
WHERE
	unit_price > (SELECT AVG(UNIT_PRICE) FROM dim_product)
)
SELECT 
	* 
FROM 
	CTE_TABLE
WHERE
	PRODUCT_NAME IN ('FIGURE METHOD' ,'HUGE CHANGE','FILM FINALLY');


